#!/usr/bin/env python3
"""w25 pilot: reads results/pilot-1/*.raw.csv (never modifies them) and writes results/pilot-1/summary.md and summary.csv.
Ratio = default time / setting time (> 1 means the setting is faster). Default = sha3-b8-q40.
'paired' ratios: for each repetition, the default's time of that repetition over the setting's time of the same repetition
(the points are interleaved, so one repetition = one round-robin pass)."""
import csv
import os
import statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "pilot-1")
DEFAULT = "sha3-b8-q40"
ORDER = ["sha3-b8-q40", "blake3-b8-q40", "sha3-b16-q37", "blake3-b16-q37"]


def read(name):
    path = os.path.join(OUT, name)
    if not os.path.exists(path):
        return []
    lines = [l for l in open(path) if not l.startswith("#") and l.strip()]
    return list(csv.DictReader(lines))


def f(x):
    return float(x)


def stats(v):
    return st.median(v), min(v), max(v), len(v)


def fmt_t(v, d=4):
    m, lo, hi, n = stats(v)
    return f"{m:.{d}f} ({lo:.{d}f}-{hi:.{d}f})"


def spread(v):
    m, lo, hi, _ = stats(v)
    return (hi - lo) / m if m else float("nan")


def table_prove(rows, field, key_n="n", title="", unit="s", scale=1.0, d=4, label_key="label"):
    """rows: dicts. Group by (n, label), timed rows only."""
    out = []
    by = {}
    for r in rows:
        if r["phase"] != "timed":
            continue
        by.setdefault((int(r[key_n]), r[label_key]), {})[int(r["rep"])] = r
    ns = sorted({k[0] for k in by})
    out.append(f"### {title}")
    out.append("")
    out.append(f"| N_Q | setting | runs | median {unit} (min-max) | spread (max-min)/median | ratio of medians | paired ratio median (min-max) | trace rows |")
    out.append("|---|---|---|---|---|---|---|---|")
    csv_rows = []
    for n in ns:
        base = by.get((n, DEFAULT), {})
        for lab in ORDER:
            g = by.get((n, lab))
            if not g:
                continue
            v = [f(g[r][field]) * scale for r in sorted(g)]
            m, lo, hi, cnt = stats(v)
            bv = [f(base[r][field]) * scale for r in sorted(base)]
            if bv:
                rm = st.median(bv) / m
                pr = [f(base[r][field]) / f(g[r][field]) for r in sorted(g) if r in base]
                prs = f"{st.median(pr):.3f} ({min(pr):.3f}-{max(pr):.3f})"
            else:
                rm, prs, pr = float("nan"), "", []
            rows_ = sorted({g[r].get("trace_rows", "") for r in g})
            out.append(f"| {n} | {lab} | {cnt} | {m:.{d}f} ({lo:.{d}f}-{hi:.{d}f}) | {spread(v):.1%} | {rm:.3f} | {prs} | {','.join(rows_)} |")
            csv_rows.append([title, n, lab, cnt, m, lo, hi, spread(v), rm, st.median(pr) if pr else "", min(pr) if pr else "", max(pr) if pr else ""])
    out.append("")
    return out, csv_rows


def main():
    md = ["# Pilot-1 summary (generated by scripts/pilot_summary.py from the raw CSVs)", "",
          "Laptop Intel Core Ultra 7 165H, 22 logical cores, shared. Absolute times are NOT comparable to the paper (Xeon, cloud); only the ratios are meaningful.",
          "Ratio = default (sha3-b8-q40) time / setting time; above 1 = the setting is faster. Timed runs only (warm-up runs are in the raw CSV).", ""]
    allc = [["table", "n", "setting", "runs", "median", "min", "max", "spread", "ratio_of_medians", "paired_median", "paired_min", "paired_max"]]

    m1 = read("m1_exec_prove.raw.csv")
    if m1:
        t, c = table_prove(m1, "prove_s", title="M1: R_Exec prove_s (block 100)")
        md += t
        allc += c
        t, c = table_prove(m1, "trace_s", title="M1: R_Exec trace-build time trace_s (not in prove_s)")
        md += t
        allc += c
        # proof bytes and security
        md.append("### M1: proof bytes (median over timed runs) and library security estimates")
        md.append("")
        md.append("| N_Q | setting | proof bytes median (min-max) | conj | udr | ldr | VmRSS kB at end of last run |")
        md.append("|---|---|---|---|---|---|---|")
        by = {}
        for r in m1:
            if r["phase"] == "timed":
                by.setdefault((int(r["n"]), r["label"]), []).append(r)
        for (n, lab) in sorted(by, key=lambda k: (k[0], ORDER.index(k[1]))):
            g = by[(n, lab)]
            b = [f(r["proof_bytes"]) for r in g]
            sec = sorted({(r["conj"], r["udr"], r["ldr"]) for r in g})
            md.append(f"| {n} | {lab} | {st.median(b):.0f} ({min(b):.0f}-{max(b):.0f}) | {'/'.join(s[0] for s in sec)} | {'/'.join(s[1] for s in sec)} | {'/'.join(s[2] for s in sec)} | {g[-1]['vmrss_kb']} |")
        md.append("")

    m2 = read("m2_bundle_verify.raw.csv")
    if m2:
        t, c = table_prove(m2, "total_s", title="M2: verify of one request bundle (R_RC + R_Auth + R_Exec proofs, 1000 records), total_s in ms", unit="ms", scale=1000.0, d=3)
        md += t
        allc += c
        md.append("### M2: proof bytes of the bundle (one proof set per child process, proven at start-up)")
        md.append("")
        md.append("| setting | bundle bytes | rc | auth | exec | conj | udr | ldr |")
        md.append("|---|---|---|---|---|---|---|---|")
        seen = {}
        for r in m2:
            seen.setdefault(r["label"], r)
        for lab in ORDER:
            r = seen.get(lab)
            if r:
                md.append(f"| {lab} | {r['bytes_total']} | {r['b_rc']} | {r['b_auth']} | {r['b_exec']} | {r['conj']} | {r['udr']} | {r['ldr']} |")
        md.append("")
        for part, title in (("t_exec", "M2 detail: exec proof only (ms)"), ("t_rc", "M2 detail: rc proof only (ms)"), ("t_auth", "M2 detail: auth proof only (ms)")):
            t, c = table_prove(m2, part, title=title, unit="ms", scale=1000.0, d=3)
            md += t
            allc += c

    side = read("side_block_exec20000.raw.csv")
    if side:
        md.append("### Side check: block 100 vs block 500 (default build, exec N_Q = 20000)")
        md.append("")
        md.append("| point | runs | prove_s median (min-max) | trace_rows |")
        md.append("|---|---|---|---|")
        by = {}
        for r in side:
            if r["phase"] == "timed":
                by.setdefault(r["label"], []).append(r)
        for lab, g in by.items():
            md.append(f"| {lab} | {len(g)} | {fmt_t([f(r['prove_s']) for r in g])} | {','.join(sorted({r['trace_rows'] for r in g}))} |")
        md.append("")

    m3 = read("m3_rc_prove.raw.csv")
    if m3:
        t, c = table_prove(m3, "prove_s", title="M3: R_RC prove_s, N_Q = 20000 (block 100)")
        md += t
        allc += c

    single = read("l3_single.raw.csv")
    chunks = read("l3_chunks.raw.csv")
    if single and chunks:
        md.append("### L3: single proof vs trace-row split (independent chunk proofs, NOT linked), block 500")
        md.append("")
        dp = read("l3_dp.csv")
        if dp:
            md.append("DP result (whole blocks of 501 words x 8 rows, each chunk padded to a power of two, min 32, at most 4 chunks):")
            md.append("")
            md.append("| N_Q | blocks | single padded rows | chunks | blocks per chunk | rows per chunk | sum of padded rows | rows single / split |")
            md.append("|---|---|---|---|---|---|---|---|")
            for r in dp:
                md.append(f"| {r['n_q']} | {r['blocks_of_500']} | {r['single_padded_rows']} | {r['best_chunks']} | {r['blocks_per_chunk']} | {r['rows_per_chunk']} | {r['split_padded_rows_sum']} | {r['ratio_rows_single_over_split']} |")
            md.append("")
        sg, ck = {}, {}
        for r in single:
            if r["phase"] == "timed":
                n = int(r["label"].rsplit("-n", 1)[1])
                sg.setdefault(n, {})[int(r["rep"])] = r
        for r in chunks:
            if r["phase"] == "timed":
                n = int(r["label"].rsplit("-n", 1)[1])
                ck.setdefault(n, {})[int(r["rep"])] = r
        md.append("| N_Q | metric | single median (min-max) | split median (min-max) | ratio of medians single/split | paired ratio median (min-max) | rows single | rows split (each) |")
        md.append("|---|---|---|---|---|---|---|---|")
        for n in sorted(sg):
            if n not in ck:
                continue
            reps = sorted(set(sg[n]) & set(ck[n]))
            if not reps:
                continue
            defs = [
                ("prove_s (sum over chunks for split)", lambda r: f(r["prove_s"]), lambda r: f(r["prove_s_sum"])),
                ("trace_s + prove_s", lambda r: f(r["trace_s"]) + f(r["prove_s"]), lambda r: f(r["trace_s_sum"]) + f(r["prove_s_sum"])),
                ("verify_s (sum over chunks for split)", lambda r: f(r["verify_s"]), lambda r: f(r["verify_total"])),
                ("proof bytes (sum for split)", lambda r: f(r["proof_bytes"]), lambda r: f(r["bytes_sum"])),
            ]
            for name, fs, fc in defs:
                a = [fs(sg[n][i]) for i in reps]
                b = [fc(ck[n][i]) for i in reps]
                pr = [x / y for x, y in zip(a, b)]
                d = 4 if "bytes" not in name else 0
                md.append(f"| {n} | {name} | {fmt_t(a, d)} | {fmt_t(b, d)} | {st.median(a) / st.median(b):.3f} | {st.median(pr):.3f} ({min(pr):.3f}-{max(pr):.3f}) | {sg[n][reps[0]]['trace_rows']} | {ck[n][reps[0]]['rows_each']} |")
                allc.append(["L3 " + name, n, "single/split", len(reps), st.median(a), min(a), max(a), "", st.median(a) / st.median(b), st.median(pr), min(pr), max(pr)])
            sec = sorted({(ck[n][i]['conj'], ck[n][i]['udr'], ck[n][i]['ldr']) for i in reps})
            md.append(f"| {n} | security conj/udr/ldr (min over chunks) | {sorted({(sg[n][i]['conj'], sg[n][i]['udr'], sg[n][i]['ldr']) for i in reps})} | {sec} | | | | |")
        md.append("")

    with open(os.path.join(OUT, "summary.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(OUT, "summary.csv"), "w", newline="") as fh:
        csv.writer(fh).writerows(allc)
    print("\n".join(md))


if __name__ == "__main__":
    main()
